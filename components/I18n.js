function normalize(language) {
  return String(language || "").toLowerCase().indexOf("es") === 0
    ? "es-419"
    : DEFAULT_LANGUAGE
}

function table(language) {
  return normalize(language) === "es-419" ? ES : EN
}

function t(language, key, values) {
  var selected = table(language)
  var result = selected[key] !== undefined ? selected[key] : EN[key]
  if (result === undefined) result = key
  result = String(result)
  var replacements = values || ({})
  for (var name in replacements)
    result = result.split("{" + name + "}").join(String(replacements[name]))
  return result
}

function interfaceLanguage(systemLocale) {
  return normalize(systemLocale)
}

function bibleLanguage(systemLocale) {
  var locale = String(systemLocale || "").replace(/_/g, "-")
  var match = locale.match(/^([A-Za-z]{2,3})/)
  return match ? match[1].toLowerCase() : "en"
}
